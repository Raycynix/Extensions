namespace Raycynix.Extensions.Contracts.Constants;

/// <summary>
/// Defines standard transport headers for contract versioning.
/// </summary>
public static class ContractHeaders
{
    /// <summary>
    /// Gets the standard contract name header.
    /// </summary>
    public const string ContractName = "X-Contract-Name";

    /// <summary>
    /// Gets the standard contract version header.
    /// </summary>
    public const string ContractVersion = "X-Contract-Version";
}
